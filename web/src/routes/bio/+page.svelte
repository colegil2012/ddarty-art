      <p class="bio__lede">
        I paint the Ohio River, mostly. The same four or five miles of it,
        over and over, at whatever hour the light does something I have not
        already recorded.
      </p>

      <p>
        That sounds like a limitation, and for the first few years it was. I
        came out of a program where the expectation was range — a portrait, a
        still life, an abstraction, proof you could do all of it. What I found
        instead was that returning to one subject long enough turns it into a
        different subject. The river in November is not the river in June wearing
        a coat. It is a separate problem with separate colors.
      </p>

      <h2 class="bio__h2">How the work gets made</h2>

      <p>
        Nearly everything starts outdoors on paper — graphite, sometimes ink,
        usually in under an hour. Most of those drawings do not become
        paintings. The ones that do get built up slowly in oil over several
        weeks, on linen when the piece is large and panel when it is small.
      </p>

      <p>
        I sand back more than I add. A finished piece has usually been mostly
        destroyed at least twice, and the under-layers showing through the
        surface are not an accident.
      </p>

      <h2 class="bio__h2">Commissions</h2>

      <p>
        I take a small number of commissions each year, mostly landscapes and
        occasionally portraits worked from photographs. The process starts with
        a conversation about what you are actually after, followed by a few
        small studies before anything larger begins.
      </p>

      <p>
        Six to ten weeks is typical from first conversation to a finished piece,
        longer for large work. If you have a date in mind, tell me early.
      </p>

